def svg_bar(x, y, w, h, frac, cls, extra=0.0, extra_cls=None):
    """Track plus a filled part with rounded ends; `extra` stacks a second
    part after the first, 2px apart."""
    parts = [f'<rect class="track" x="{x}" y="{y}" width="{w}" height="{h}" rx="{h / 2:g}"/>']
    fw = round(w * max(0.0, min(1.0, frac)), 1)
    if fw > 0:
        parts.append(f'<rect class="{cls}" x="{x}" y="{y}" width="{max(fw, h)}" height="{h}" rx="{h / 2:g}"/>')
    ew = round(w * max(0.0, min(1.0, frac + extra)), 1) - fw - (2 if fw > 0 else 0)
    if extra_cls and ew > 0:
        ex = x + fw + (2 if fw > 0 else 0)
        parts.append(f'<rect class="{extra_cls}" x="{ex:g}" y="{y}" width="{max(ew, h):g}" height="{h}" rx="{h / 2:g}"/>')
    return parts


def svg_text(x, y, s, cls="ink", size=12, anchor="start", weight=None):
    w = f' font-weight="{weight}"' if weight else ""
    return (f'<text class="{cls} num" x="{x}" y="{y}" font-size="{size}" text-anchor="{anchor}"{w}>'
            f'{escape(str(s))}</text>')


def render_svg(fw_total, game_total, lib_rows, op_rows, top=20):
    width = 1000
    row_h = 24
    head = 128
    left_rows = lib_rows[:top]
    n_rows = max(len(left_rows), len(op_rows))
    height = head + 62 + n_rows * row_h + 26
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}" '
           f'role="img" aria-label="rps5e implementation progress">',
           f"<style>{SVG_STYLE}</style>", f'<rect class="bg" x="0" y="0" width="{width}" height="{height}" rx="8"/>']

    # Headline tiles.
    tiles = [("Firmware 3.20 functions", fw_total["implemented"], fw_total["total"], "with an HLE implementation"),
             ("Functions our games import", game_total["hle"], game_total["imported"], "resolved"),
             ("System libraries", fw_total["modules_touched"], fw_total["modules"], "with at least one function"),
             ("RDNA instructions", game_total["ops_done"], game_total["ops_total"], "decoded (RDNA 1 + 2 list)")]
    tw = (width - 32 - 3 * 16) / 4
    for i, (label, a, b, note) in enumerate(tiles):
        x = 16 + i * (tw + 16)
        value = f"{pct1(a, b):.1f}%" if label != "System libraries" else f"{a} / {b}"
        out.append(f"<g><title>{escape(label)}: {a} / {b}</title>")
        out.append(svg_text(x, 34, label, "ink2", 13))
        out.append(svg_text(x, 70, value, "ink", 30, weight="600"))
        if label != "Functions our games import":
            sub = f"{a:,} / {b:,} {note}" if label != "System libraries" else note
            out.append(svg_text(x, 92, sub, "mute", 11.5))
        if label == "Functions our games import":
            # Imports the game's own modules serve are resolved too: HLE
            # plus own modules, the rest are stubs.
            lle = game_total.get("lle", 0)
            out[-3] = f"<g><title>{escape(label)}: {a} HLE + {lle} game's own modules of {b}</title>"
            out[-1] = svg_text(x, 70, f"{pct1(a + lle, b):.1f}%", "ink", 30, weight="600")
            out.append(svg_text(x, 92, f"{a:,} HLE + {lle:,} own modules, {b - a - lle:,} stubs", "mute", 11.5))
            out += svg_bar(x, 104, tw, 6, a / b if b else 0, "s2", lle / b if b else 0, "s2l")
            out.append("</g>")
            continue
        out += svg_bar(x, 104, tw, 6, a / b if b else 0, "s1")
        out.append("</g>")
    out.append(f'<line class="rule" x1="16" x2="{width - 16}" y1="{head}" y2="{head}" stroke-width="1"/>')

    # Left: libraries our games import.
    lx, label_w, bar_w = 16, 168, 250
    y0 = head + 26
    out.append(svg_text(lx, y0, "Libraries our games import (most imported first)", "ink", 13, weight="600"))
    # Legend.
    ly = y0 + 14
    out.append(f'<rect class="s1" x="{lx}" y="{ly - 8}" width="10" height="10" rx="2"/>')
    out.append(svg_text(lx + 14, ly + 1, "of the library's firmware functions", "ink2", 11))
    out.append(f'<rect class="s2" x="{lx + 204}" y="{ly - 8}" width="10" height="10" rx="2"/>')
    out.append(svg_text(lx + 218, ly + 1, "of the imports: HLE", "ink2", 11))
    out.append(f'<rect class="s2l" x="{lx + 326}" y="{ly - 8}" width="10" height="10" rx="2"/>')
    out.append(svg_text(lx + 340, ly + 1, "game's own module", "ink2", 11))
    y = ly + 22
    for r in left_rows:
        lib = r["library"]
        name = lib if len(lib) <= 26 else lib[:25] + "…"
        out.append(f'<g><title>{escape(lib)}: {r["implemented"]}/{r["total"]} functions implemented; '
                   f'games import {r["imported"]}, {r["hle"]} in HLE, {r["lle"]} from the game\'s own modules</title>')
        out.append(svg_text(lx, y + 11, name, "ink", 12))
        out += svg_bar(lx + label_w, y, bar_w, 6, r["implemented"] / r["total"] if r["total"] else 0, "s1")
        imp = r["imported"] or 1
        out += svg_bar(lx + label_w, y + 8, bar_w, 6, r["hle"] / imp, "s2", r["lle"] / imp, "s2l")
        tx = lx + label_w + bar_w + 8
        out.append(svg_text(tx, y + 6, f'{pct(r["implemented"], r["total"])} of {r["total"]}', "ink2", 10.5))
        lle = f' + {pct(r["lle"], r["imported"])}' if r["lle"] else ""
        out.append(svg_text(tx, y + 16, f'{pct(r["hle"], r["imported"])}{lle} of {r["imported"]} imported', "ink2", 10.5))
        out.append("</g>")
        y += row_h

    # Right: shader instructions per encoding.
    rx0, rlabel, rbar = 610, 64, 250
    out.append(svg_text(rx0, y0, "RDNA instructions decoded, per encoding", "ink", 13, weight="600"))
    y = ly + 22
    for r in op_rows:
        out.append(f'<g><title>{r["encoding"]}: {r["implemented"]}/{r["total"]}</title>')
        out.append(svg_text(rx0, y + 11, r["encoding"], "ink", 12))
        out += svg_bar(rx0 + rlabel, y + 3, rbar, 8, r["implemented"] / r["total"] if r["total"] else 0, "s1")
        out.append(svg_text(rx0 + rlabel + rbar + 8, y + 11,
                            f'{r["implemented"]}/{r["total"]}', "ink2", 10.5))
        out.append("</g>")
        y += row_h

    out.append(svg_text(16, height - 14, "Generated by progress/progress.py (make stats). Function list: firmware 3.20 "
                        "stub libraries (named exports only). Implemented = real HLE callback, not a 0x80020002 stub.",
                        "mute", 10.5))
    out.append("</svg>")
    return "\n".join(out) + "\n"


