def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-games", action="store_true")
    ap.add_argument("--games-dir", default=os.environ.get("GAMES_DIR") or local_games_dir())
    ap.add_argument("--fw-libs", default=os.environ.get("PS5_FW_LIBS"),
                    help="PS5-3.20_Libs checkout (default: local/other_emus/PS5-3.20_Libs in this tree or a parent)")
    ap.add_argument("--out", default=os.path.join(ROOT, "progress", "PROGRESS_STATS"))
    ap.add_argument("--svg", default=os.path.join(ROOT, "progress", "progress.svg"))
    a = ap.parse_args()

    reg = registry()
    cat = catalog()
    fw_dir = find_fw_libs(a.fw_libs)
    game_rows = [] if a.no_games or not a.games_dir else sorted(games(a.games_dir), key=lambda g: g["game"].lower())
    ops, missing = opcodes()
    o_done = sum(r["implemented"] for r in ops)
    o_all = sum(r["total"] for r in ops)

    md = ["# Implementation statistics", "",
          "Generated by `progress/progress.py` (`make stats`). Raw numbers: `PROGRESS_STATS.json`, picture: `progress.svg`.", ""]
    data = {"games": [{k: v for k, v in g.items() if k != "imports"} for g in game_rows],
            "opcodes": ops, "opcodes_missing": missing}

    if fw_dir:
        fw = firmware(fw_dir)
        owner = owner_map(fw, reg)
        libs, total = fw_coverage(fw, reg)
        glibs, outside = game_libraries(game_rows, fw, owner, reg)
        src = source_check(fw, cat)
        g_imp = sum(r["imported"] for r in glibs)
        g_hle = sum(r["hle"] for r in glibs)
        g_lle = sum(r["lle"] for r in glibs)
        gl_done = sum(r["implemented"] for r in glibs)
        gl_all = sum(r["total"] for r in glibs)
        md += ["## Summary", "",
               f"- Firmware 3.20 functions with an HLE implementation: **{total['implemented']} of {total['total']} "
               f"({pct1(total['implemented'], total['total'])}%)**, in {total['modules_touched']} of {total['modules']} "
               f"system libraries ({total['modules_complete']} complete).",
               ]
        if game_rows:
            md += [f"- Libraries our games import from: **{len(glibs)}**; their functions implemented: "
                   f"**{gl_done} of {gl_all} ({pct1(gl_done, gl_all)}%)**.",
                   f"- Functions the games import from them: **{g_hle} of {g_imp} ({pct1(g_hle, g_imp)}%)** in HLE, "
                   f"{g_lle} more bound to the game's own modules (LLE)."]
        md += [f"- RDNA instructions decoded: **{o_done} of {o_all} ({pct1(o_done, o_all)}%)**.", ""]
        if game_rows:
            md += _games_md(game_rows, True)
            md += ["## Libraries the games import", "",
                   "Unique imports of all games, placed in the firmware module that exports the NID. Imported: HLE "
                   "(our implementation), LLE (the game's own module exports it), stub (returns `0x80020002`). "
                   "Library: all functions of that firmware module.", "",
                   "| Library | Imported | HLE | LLE | Stub | HLE % | Library implemented | Library total | Library % |",
                   "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
            for r in glibs:
                md.append(f"| {r['library']} | {r['imported']} | {r['hle']} | {r['lle']} | {r['stub']} | "
                          f"{pct(r['hle'], r['imported'])} | {r['implemented']} | {r['total']} | {pct(r['implemented'], r['total'])} |")
            md += [f"| **Total** | **{g_imp}** | **{g_hle}** | **{g_lle}** | | **{pct(g_hle, g_imp)}** | **{gl_done}** | "
                   f"**{gl_all}** | **{pct(gl_done, gl_all)}** |", ""]
            if outside:
                md += ["Imported NIDs the 3.20 list does not have, not counted above. Named: functions added after "
                       "firmware 3.20 (the catalog knows the name); unnamed: NIDs nobody has named yet, mostly imports "
                       "of modules the game loads itself at run time: "
                       + ", ".join(f"{k} {v}" for k, v in sorted(outside.items())) + ".", ""]
        md += ["## System libraries (firmware 3.20)", "",
               "Every module of the firmware 3.20 stub libraries with at least one registered export. Stub: registered "
               "from the NID catalog, returns `0x80020002`. A NID several modules re-export counts in each of them; "
               "the total counts it once.", "",
               "| Library | Implemented | Stub | Total | % |", "|---|---:|---:|---:|---:|"]
        for r in libs:
            if r["implemented"] or r["stub"]:
                md.append(f"| {r['library']} | {r['implemented']} | {r['stub']} | {r['total']} | {pct(r['implemented'], r['total'])} |")
        untouched = [r for r in libs if not r["implemented"]]
        md += [f"| **Total (unique NIDs)** | **{total['implemented']}** | | **{total['total']}** | "
               f"**{pct(total['implemented'], total['total'])}** |", "",
               f"{len(untouched)} modules have no implemented function (only catalog stubs): "
               + ", ".join(r["library"] for r in sorted(untouched, key=lambda r: r["library"].lower())) + ".", ""]
        if total["implemented_outside"]:
            md += ["Implemented exports the 3.20 list does not have (newer functions, aliases): "
                   + ", ".join(f"{k} {v}" for k, v in sorted(total["implemented_outside"].items())) + ".", ""]
        md += ["## Source", "",
               f"`PS5-3.20_Libs` ({src['entries']} entries in {total['modules']} modules, "
               f"{src['unique_nids']} distinct NIDs) is the genstub.py output for firmware 3.20: one `.c` per system "
               "module, `sprx_dlsym(handle, \"<NID>\", &__ptr_<name>)` per export.", "",
               f"- {src['verified']} of {src['entries']} entries have NID = SHA1(name + salt): names and NIDs are right.",
               "- Only exports with a known name are listed; the firmware exports more (unnamed NIDs are dropped), so "
               "the totals are a lower bound.",
               "- It is firmware 3.20: functions added later are missing (game imports outside the list above).",
               "- Per module, not per library: libkernel mixes libkernel, libScePosix and the other libraries of the "
               "module; libkernel_sys/_web, libSceNKWebKit (libSceJsc), libSceAgcVsh (libSceAgc) re-export others.",
               "- Data symbols are listed like functions; modules games ship themselves (libc.prx, middleware) are not "
               "in it.",
               f"- Against our NID catalog (`crates/ps5nid/data/merged_exports.tsv`, {src['catalog']} entries): "
               f"{src['catalog_in_fw']} (NID, module) pairs agree; {src['fw_not_in_catalog']} firmware NIDs are "
               f"missing from it ({src['fw_reexports_elsewhere']} module re-exports are filed there under one library "
               "only); the catalog has these entries the firmware list does not:", ""]
        for reason, n in sorted(src["catalog_not_in_fw"].items(), key=lambda kv: -kv[1]):
            md.append(f"  - {n}: {reason}")
        md.append("")
        data.update({"firmware": {"dir": os.path.basename(os.path.normpath(fw_dir)),
                                  "total": total, "libraries": libs, "source": src},
                     "game_libraries": glibs, "game_imports_outside_fw": outside})
        game_total = {"hle": g_hle, "lle": g_lle, "imported": g_imp, "ops_done": o_done, "ops_total": o_all}
        if game_rows:
            with open(a.svg, "w", encoding="utf-8") as fh:
                fh.write(render_svg(total, game_total, glibs, ops))
        else:
            print(f"--no-games: {a.svg} left as it is (the picture needs the game imports)", file=sys.stderr)
    else:
        print("firmware 3.20 stub libraries not found (--fw-libs / PS5_FW_LIBS): catalog only, no picture",
              file=sys.stderr)
        if game_rows:
            md += _games_md(game_rows, False)
        libs = catalog_coverage(cat, reg)
        t_done = sum(r["implemented"] for r in libs)
        t_all = sum(r["total"] for r in libs)
        md += ["## System libraries (NID catalog)", "", "The firmware 3.20 list was not found; this is the NID catalog.", "",
               "| Library | Implemented | Stub | Total | % |", "|---|---:|---:|---:|---:|"]
        for r in libs:
            if r["implemented"] or r["stub"]:
                md.append(f"| {r['library']} | {r['implemented']} | {r['stub']} | {r['total']} | {pct(r['implemented'], r['total'])} |")
        md += [f"| **Total** | **{t_done}** | | **{t_all}** | **{pct(t_done, t_all)}** |", ""]
        data["catalog_libraries"] = libs

    md += ["## GPU shader instructions (decoder)", "", "AMD RDNA 1 + RDNA 2 list (`progress/data/rdna_isa.txt`). Decoded is not translated.", "",
           "| Encoding | Decoded | Total | % |", "|---|---:|---:|---:|"]
    for r in ops:
        md.append(f"| {r['encoding']} | {r['implemented']} | {r['total']} | {pct(r['implemented'], r['total'])} |")
    md += [f"| **Total** | **{o_done}** | **{o_all}** | **{pct(o_done, o_all)}** |", ""]
    if missing:
        md += ["Not decoded:", ""]
        for enc, names in sorted(missing.items()):
            md.append(f"- {enc}: " + ", ".join(n.lower() for n in names))
        md.append("")

    with open(a.out + ".md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(md))
    with open(a.out + ".json", "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=1)
    if fw_dir:
        print(f"firmware functions {total['implemented']}/{total['total']} ({pct1(total['implemented'], total['total'])}%), "
              f"libraries {total['modules_touched']}/{total['modules']}, "
              f"game imports {g_hle}/{g_imp} ({pct1(g_hle, g_imp)}%), "
              f"opcodes {o_done}/{o_all} ({pct1(o_done, o_all)}%) -> {a.out}.md, {a.svg}")
    else:
        print(f"opcodes {o_done}/{o_all} ({pct1(o_done, o_all)}%) -> {a.out}.md")


def _games_md(game_rows, with_fw):
    md = ["## Game imports", "",
          "Imports of each game's eboot.bin: bound to HLE, to the game's own modules (LLE), or to stubs that return "
          "`0x80020002`. The listing is static: imports from modules the game loads itself at run time "
          "(`sceKernelLoadStartModule`) are bound when they load and show here as stubs, mostly with NIDs the catalog "
          "does not name." + (" In FW 3.20: imports the firmware 3.20 list has, and how many of them are HLE." if with_fw else ""),
          ""]
    head = "| Game | HLE | LLE | Stub | Total | Bound |" + (" In FW 3.20 | HLE of those |" if with_fw else "")
    md += [head, "|---|---:|---:|---:|---:|---:|" + ("---:|---:|" if with_fw else "")]
    for g in game_rows:
        if "error" in g:
            md.append(f"| {g['game']} | — | — | — | — | {g['error'][:60]} |" + (" | |" if with_fw else ""))
            continue
        line = f"| {g['game']} | {g['hle']} | {g['lle']} | {g['stub']} | {g['total']} | {pct(g['hle'] + g['lle'], g['total'])} |"
        if with_fw:
            line += f" {g['in_fw']} | {pct(g['in_fw_hle'], g['in_fw'])} |"
        md.append(line)
    md.append("")
    return md


