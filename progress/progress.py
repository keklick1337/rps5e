ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIN = os.path.join(ROOT, "target", "release")
CATALOG = os.path.join(ROOT, "crates", "ps5nid", "data", "merged_exports.tsv")
ISA = os.path.join(ROOT, "progress", "data", "rdna_isa.txt")
# Looked up in local/ of this tree or a parent (local files are not in git).
FW_LIBS = os.path.join("local", "other_emus", "PS5-3.20_Libs")
NID_SALT = bytes.fromhex("518D64A635DED8C1E6B039B1C3E55230")
IMPLEMENTED = ("fn", "fallback")

# Decoder spellings that differ from the AMD list (ours -> AMD). Several
# carry GCN-era names for the RDNA opcode they decode (VOP2 0x25-0x27 are
# v_add/sub/subrev_nc_u32 on RDNA).
OPCODE_ALIASES = {
    "v_add_i32": "v_add_nc_u32",
    "v_sub_i32": "v_sub_nc_u32",
    "v_subrev_i32": "v_subrev_nc_u32",
    "v_lshl_or_u32": "v_lshl_or_b32",
    "v_or3_u32": "v_or3_b32",
    "v_movrelsd2_b32": "v_movrelsd_2_b32",
    "s_movrelsd2_b32": "s_movrelsd_2_b32",
    "s_ttrace_data": "s_ttracedata",
    "image_gather4_h": "image_gather4h",
    "v_mad_mixlo_f16": "v_fma_mixlo_f16",
    "v_mad_mixhi_f16": "v_fma_mixhi_f16",
}
# One decoded opcode that covers several AMD names (SOPK 0x17-0x1A).
OPCODE_VARIANTS = {
    "s_waitcnt": ("s_waitcnt_vscnt", "s_waitcnt_vmcnt", "s_waitcnt_expcnt", "s_waitcnt_lgkmcnt"),
    # The list has both the RDNA 1 and the RDNA 2 spelling.
    "v_mac_legacy_f32": ("v_fmac_legacy_f32",),
    "v_mad_legacy_f32": ("v_fma_legacy_f32",),
}


def canonical(m):
    """Our mnemonic in AMD's spelling."""
    m = OPCODE_ALIASES.get(m, m)
    m = re.sub(r"atomic_([suf])_(min|max)", r"atomic_\1\2", m)
    m = re.sub(r"2_st64_", "2st64_", m)
    return m


def compute_nid(name):
    """crates/ps5nid compute_nid: SHA1(name + salt), 8 bytes, base64 with '-' for '/'."""
    value = struct.unpack("<Q", hashlib.sha1(name.encode() + NID_SALT).digest()[:8])[0]
    return base64.b64encode(struct.pack(">Q", value)).decode().rstrip("=").replace("/", "-")


def run(args):
    r = subprocess.run(args, capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"{' '.join(args)} failed ({r.returncode}): {r.stderr.strip()[:400]}")
    return r.stdout


def tool(name):
    path = os.path.join(BIN, name)
    if not os.path.exists(path):
        raise SystemExit(f"{path} is missing: run `cargo build --release` first")
    return path


def pct(a, b):
    return f"{100.0 * a / b:.0f}%" if b else "—"


def pct1(a, b):
    return round(100.0 * a / b, 1) if b else 0.0


# ---------------------------------------------------------------- inputs

def registry():
    """nid -> (name, library, kind) from the HLE registry."""
    out = {}
    for line in run([tool("rps5e-cli"), "hle-exports"]).splitlines()[1:]:
        nid, name, lib, kind = line.split("\t")
        out[nid] = (name, lib, kind)
    return out


def catalog():
    """(nid, library) -> name from our NID catalog."""
    out = {}
    with open(CATALOG, encoding="utf-8") as fh:
        next(fh)
        for line in fh:
            parts = line.rstrip("\n").split("\t")
            if len(parts) >= 3:
                out[(parts[0], parts[2])] = parts[1]
    return out


def find_fw_libs(given):
    if given:
        return given if os.path.isdir(given) else None
    d = ROOT
    while True:
        cand = os.path.join(d, FW_LIBS)
        if os.path.isdir(cand):
            return cand
        parent = os.path.dirname(d)
        if parent == d:
            return None
        d = parent


DLSYM = re.compile(r'sprx_dlsym\(__handle,\s*"([^"]+)",\s*&__ptr_([^)\s]+)\)')
DLOPEN = re.compile(r'sprx_dlopen\("([^"]+)"')


def firmware(path):
    """module -> {nid: name} from the genstub.py stub sources.

    libkernel, libkernel_sys, libkernel_web and libSceLibcInternal use a
    fixed handle instead of sprx_dlopen: their module is the file name."""
    fw = {}
    for f in sorted(os.listdir(path)):
        if not f.endswith(".c"):
            continue
        with open(os.path.join(path, f), encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        m = DLOPEN.search(text)
        module = m.group(1) if m else f[:-2]
        fw[module] = dict(DLSYM.findall(text))
    return fw


def owner_map(fw, reg):
    """nid -> the module a game gets it from. A NID several modules export
    goes to the module our registry files it under, else to the shortest
    module name (libkernel before libkernel_sys/_web, libSceJsc before
    libSceNKWebKit, libSceAgc before libSceAgcVsh)."""
    where = defaultdict(list)
    for module, nids in fw.items():
        for nid in nids:
            where[nid].append(module)
    owner = {}
    for nid, mods in where.items():
        lib = reg.get(nid, (None, None))[1]
        owner[nid] = lib if lib in mods else min(mods, key=lambda m: (len(m), m))
    return owner


