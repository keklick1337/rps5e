"""Implementation statistics: firmware library functions, game imports, shader opcodes.

Usage: python3 -I progress/progress.py [--no-games] [--fw-libs DIR] [--out progress/PROGRESS_STATS]
                                       [--svg progress/progress.svg]

Writes <out>.md (tables), <out>.json (raw numbers) and the README picture
(progress/progress.svg, plain SVG). Needs the release binaries (`cargo build
--release`); nothing is executed besides the static listing commands below,
no game is run.

- Firmware functions: the stub libraries of firmware 3.20
  (local/other_emus/PS5-3.20_Libs, one <module>.c per system module, generated by
  genstub.py; found in this tree or a parent of it, or given with --fw-libs)
  against the HLE registry (`rps5e-cli hle-exports`). A function counts as
  implemented when it has a real HLE callback (`fn`, or a `fallback` used
  when the module does not export it); stubs that return 0x80020002 do not.
  Matching is by NID, so a function counts in every module that re-exports
  it, and the overall total counts each NID once.
- Games: `rps5e-cli imports` of every eboot.bin under --games-dir
  (GAMES_DIR from the environment or local/games.conf; none: no game
  section): imports bound to HLE, to the game's own modules
  (LLE) and to stubs; each imported NID is placed in the firmware module
  that exports it.
- Shader opcodes: the AMD RDNA 1 + RDNA 2 instruction list
  (progress/data/rdna_isa.txt) against the opcodes the decoder names
  (`ps5shader-dis --list-opcodes`). Decoded is not the same as translated:
  the translator may still refuse an opcode it decodes.

How far the firmware 3.20 list can be trusted (the numbers are recomputed in
the "Source" section of the report):
- every entry is `sprx_dlsym(handle, "<NID>", &__ptr_<name>)` and every NID
  equals SHA1(name + salt): names and NIDs are right;
- only exports with a known name are listed: the generator drops NIDs it
  cannot name, so the real firmware exports more than the list has;
- it is firmware 3.20: functions added later (newer SDK revisions, `_04_00`
  style variants) are missing, which shows as game imports outside the list;
- one file per module (.sprx), not per library: libkernel's file mixes
  libkernel, libScePosix and the other libraries of that module, and a few
  modules re-export another module's functions (libkernel_sys/_web,
  libSceNKWebKit has libSceJsc, libSceAgcVsh has libSceAgc);
- data symbols are listed like functions; modules a game ships itself
  (libc.prx, middleware) are not in it.
"""
