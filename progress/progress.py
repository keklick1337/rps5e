def fw_coverage(fw, reg):
    rows = []
    for module, nids in fw.items():
        kinds = Counter(reg[n][2] for n in nids if n in reg)
        rows.append({"library": module, "implemented": kinds["fn"] + kinds["fallback"], "stub": kinds["stub"],
                     "total": len(nids)})
    rows.sort(key=lambda r: (-r["implemented"], -r["total"], r["library"]))
    all_nids = {n for nids in fw.values() for n in nids}
    done = sum(1 for n in all_nids if reg.get(n, ("", "", ""))[2] in IMPLEMENTED)
    outside = Counter(lib for n, (_, lib, k) in reg.items() if k in IMPLEMENTED and n not in all_nids)
    return rows, {"implemented": done, "total": len(all_nids), "modules": len(fw),
                  "entries": sum(len(v) for v in fw.values()),
                  "modules_touched": sum(1 for r in rows if r["implemented"]),
                  "modules_complete": sum(1 for r in rows if r["total"] and r["implemented"] == r["total"]),
                  "implemented_outside": dict(outside)}


def source_check(fw, cat):
    """How the firmware list and our catalog agree (for the report)."""
    entries = [(m, n, name) for m, d in fw.items() for n, name in d.items()]
    verified = sum(1 for _, n, name in entries if compute_nid(name) == n)
    pairs = {(n, m) for m, n, _ in entries}
    fw_nids = {n for _, n, _ in entries}
    reasons = Counter()
    for (nid, lib), name in cat.items():
        if (nid, lib) in pairs:
            continue
        real = compute_nid(name)
        if real != nid and real.replace("-", "_") == nid.replace("-", "_"):
            reasons["NID is SHA1(name) with '_' for '-': a mis-encoded copy of a correct entry"] += 1
        elif real != nid:
            reasons["NID is not SHA1(name): placeholder or wrong name"] += 1
        elif lib not in fw:
            reasons["library name that is no firmware module (aliases, game modules)"] += 1
        elif nid in fw_nids:
            reasons["filed under another module than in the firmware list"] += 1
        else:
            reasons["named export the 3.20 list does not have (newer firmware)"] += 1
    return {"entries": len(entries), "verified": verified, "unique_nids": len(fw_nids),
            "catalog": len(cat), "catalog_in_fw": len(pairs & set(cat)),
            "fw_not_in_catalog": len(fw_nids - {n for n, _ in cat}),
            "fw_reexports_elsewhere": len({p for p in pairs - set(cat) if p[0] in {n for n, _ in cat}}),
            "catalog_not_in_fw": dict(reasons)}


def catalog_coverage(cat, reg):
    """Fallback when the firmware list is not available: per catalog library."""
    per = defaultdict(set)
    for nid, lib in cat:
        per[lib].add(nid)
    rows = []
    for lib, nids in per.items():
        kinds = Counter(reg[n][2] for n in nids if n in reg)
        rows.append({"library": lib, "implemented": kinds["fn"] + kinds["fallback"], "stub": kinds["stub"],
                     "total": len(nids)})
    rows.sort(key=lambda r: (-r["implemented"], r["library"]))
    return rows


def local_games_dir():
    """GAMES_DIR=... of local/games.conf (the developer's own paths, not in git)."""
    conf = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "local", "games.conf")
    try:
        with open(conf, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line.startswith("GAMES_DIR="):
                    return os.path.expanduser(line.split("=", 1)[1].strip().strip('"').strip("'"))
    except OSError:
        pass
    return None


def game_name(folder):
    """`Title (TITLE_ID)` from sce_sys/param.json; the folder name only when it has none."""
    try:
        with open(os.path.join(folder, "sce_sys", "param.json"), encoding="utf-8") as f:
            info = json.load(f)
    except (OSError, ValueError):
        return os.path.basename(os.path.normpath(folder))
    names = info.get("localizedParameters", {})
    lang = names.get("defaultLanguage", "en-US")
    title = (names.get(lang) or names.get("en-US") or {}).get("titleName") or os.path.basename(os.path.normpath(folder))
    tid = info.get("titleId", "")
    return f"{title} ({tid})" if tid else title


def games(games_dir):
    out = []
    for d, _, files in sorted(os.walk(games_dir)):
        if "eboot.bin" not in files:
            continue
        eboot = os.path.join(d, "eboot.bin")
        game = {"game": game_name(d)}
        try:
            text = run([tool("rps5e-cli"), "imports", eboot])
        except SystemExit as e:
            game["error"] = str(e)
            out.append(game)
            continue
        kinds = Counter()
        status = {}
        for line in text.splitlines():
            parts = line.split("\t")
            if len(parts) >= 4:
                k = parts[-1].split("@")[0]
                if k in ("HLE", "LLE", "STUB"):
                    kinds[k] += 1
                    status[parts[0]] = (k, parts[1])
        game.update({"hle": kinds["HLE"], "lle": kinds["LLE"], "stub": kinds["STUB"], "total": sum(kinds.values()),
                     "imports": status})
        out.append(game)
    return out


def game_libraries(game_rows, fw, owner, reg):
    """Firmware modules the games import from, with what the imports bind to."""
    best = {}
    rank = {"HLE": 2, "LLE": 1, "STUB": 0}
    for g in game_rows:
        for nid, (k, name) in g.get("imports", {}).items():
            if rank[k] > rank.get(best.get(nid, ("",))[0], -1):
                best[nid] = (k, name)
    per = defaultdict(Counter)
    outside = Counter()
    for nid, (k, name) in best.items():
        if nid in owner:
            per[owner[nid]][k] += 1
        else:
            outside[("unnamed" if name == "?" else "named") + " " + k] += 1
    rows = []
    for module, c in per.items():
        nids = fw[module]
        done = sum(1 for n in nids if reg.get(n, ("", "", ""))[2] in IMPLEMENTED)
        rows.append({"library": module, "imported": sum(c.values()), "hle": c["HLE"], "lle": c["LLE"], "stub": c["STUB"],
                     "implemented": done, "total": len(nids)})
    rows.sort(key=lambda r: (-r["imported"], r["library"]))
    for g in game_rows:
        imp = g.get("imports", {})
        g["in_fw"] = sum(1 for n in imp if n in owner)
        g["in_fw_hle"] = sum(1 for n, (k, _) in imp.items() if n in owner and k == "HLE")
    return rows, dict(outside)


def opcodes():
    ours = set()
    for line in run([tool("ps5shader-dis"), "--list-opcodes"]).splitlines():
        m = line.strip().lower()
        if m:
            ours.add(canonical(m))
            ours.update(OPCODE_VARIANTS.get(m, ()))
    per = defaultdict(lambda: [0, 0])
    missing = defaultdict(list)
    with open(ISA, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            name, enc = line.split()
            per[enc][1] += 1
            if name.lower() in ours:
                per[enc][0] += 1
            else:
                missing[enc].append(name)
    rows = [{"encoding": e, "implemented": d, "total": t} for e, (d, t) in sorted(per.items())]
    return rows, {e: sorted(v) for e, v in missing.items()}


